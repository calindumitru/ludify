// PROTOTYPE, never merge. Builds the brief spike page: the deck player's page (as
// scripts/build-player.ts makes it) with spike.ts in place of the bridge, spike.css, and the
// containers the spike draws into. Writes src/spike.gen.ts for the Worker, and two standalone
// pages in prototype-brief-spike/dist/ (no host) for a quick look in a browser.
// Usage: node prototype-brief-spike/build.ts
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { buildDeck } from '@ludify/deck';

const here = (p: string) => fileURLToPath(new URL(p, import.meta.url));
const page = await buildDeck(null);
const deckBlock = '<script type="application/json" id="deck">null</script>\n<script>\n';
const engineEnd = '\n</script>\n';
const out = await build({ entryPoints: [here('spike.ts')], bundle: true, format: 'iife', write: false, minify: true, target: 'es2022', charset: 'utf8' });
const spike = out.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const css = await readFile(here('spike.css'), 'utf8');
const [head, engine] = page.split(deckBlock);
const shell = (pre: string) => head
  .replace('</style>', `</style>\n<style>${css}</style>`)
  .replace('<div class="bar">', '<div id="spike-bar"></div><div id="spike-tabs" hidden></div><div id="brief-root"></div><div id="brief-layer" hidden></div>\n<div class="bar">')
  + '<script type="application/json" id="deck"></script>\n'
  + '<script>\nwindow.ludifyBoot = () => {\n' + engine.slice(0, -engineEnd.length) + '\n};\n</script>\n'
  + pre + `<script>${spike}</script>\n`;

const data = (f: string) => readFile(here(f), 'utf8').then(JSON.parse);
const [brief, deck, links] = await Promise.all([data('brief.json'), data('deck.json'), data('links.json')]);
const html = shell('');
await writeFile(here('../src/spike.gen.ts'), `// Generated by prototype-brief-spike/build.ts; do not edit. PROTOTYPE.\nexport const SPIKE_HTML = ${JSON.stringify(html)};\nexport const SPIKE_DATA = ${JSON.stringify({ brief, deck, links })};\n`);
await mkdir(here('dist'), { recursive: true });
for (const view of ['brief', 'deck']) {
  const local = `<script>window.spikeLocal=${JSON.stringify({ view, brief, deck, links }).replace(/</g, '\\u003c')};</script>\n`;
  await writeFile(here(`dist/spike-${view}.html`), shell(local));
}
await writeFile(here('dist/index.html'), `<!doctype html><meta charset="utf-8"><title>Brief spike: a fake chat</title>
<style>body{margin:0;background:#888;font:14px system-ui}.col{max-width:760px;margin:0 auto;padding:1rem;display:flex;flex-direction:column;gap:1rem}
.msg{background:#fff;border-radius:12px;padding:.6rem}.msg p{margin:.2rem .4rem .6rem}iframe{width:100%;border:0;height:720px;border-radius:8px}</style>
<div class="col"><div class="msg"><p><b>Claude:</b> here's your brief…</p><iframe src="spike-brief.html"></iframe></div>
<div class="msg"><p><b>Claude:</b> …and the deck from the same research.</p><iframe src="spike-deck.html"></iframe></div></div>`);
console.log(`src/spike.gen.ts: ${html.length} bytes; dist/ written`);
