// Builds the deck player: the page `buildDeck` writes for a deck, with the deck left empty, the
// host bridge (src/player/bridge.ts) added before the engine, and the engine wrapped in
// `window.ludifyBoot` so it starts once the bridge has the deck. Writes src/player.gen.ts, which
// the Worker imports (a Worker can't read files or run esbuild).
// Usage: node scripts/build-player.ts
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { buildDeck } from '@ludify/deck';

const here = (p: string) => fileURLToPath(new URL(p, import.meta.url));

const page = await buildDeck(null);
const deckBlock = '<script type="application/json" id="deck">null</script>\n<script>\n';
const engineEnd = '\n</script>\n';
if (page.split(deckBlock).length !== 2 || !page.endsWith(engineEnd))
  throw new Error("The deck page from @ludify/deck changed shape; update scripts/build-player.ts to match src/shell.html.");

const out = await build({ entryPoints: [here('../src/player/bridge.ts')], bundle: true, format: 'iife', write: false, minify: true, target: 'es2022', charset: 'utf8' });
const bridge = out.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');

const [head, engine] = page.split(deckBlock);
const html = head
  + '<script type="application/json" id="deck"></script>\n'
  + `<script>${bridge}</script>\n`
  + '<script>\nwindow.ludifyBoot = () => {\n'
  + engine.slice(0, -engineEnd.length)
  + '\n};\n</script>\n';

await writeFile(here('../src/player.gen.ts'), `// Generated by scripts/build-player.ts; do not edit.\nexport const PLAYER_HTML = ${JSON.stringify(html)};\n`);
console.log(`src/player.gen.ts: player page ${html.length} bytes (bridge ${bridge.length})`);
