// Builds the guide: guide.md, the deck-writing manual ludify_guide returns, into src/guide.gen.ts,
// which the Worker imports (a Worker can't read files). src/guide.test.ts keeps guide.md in step
// with the deck schema and the engine's strings.
// Usage: node scripts/build-guide.ts
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const here = (p: string) => fileURLToPath(new URL(p, import.meta.url));

const guide = await readFile(here('../guide.md'), 'utf8');
await writeFile(here('../src/guide.gen.ts'), `// Generated by scripts/build-guide.ts from guide.md; do not edit.\nexport const GUIDE = ${JSON.stringify(guide)};\n`);
console.log(`src/guide.gen.ts: guide ${guide.length} characters`);
