// Builds the narrowing form's page: the deck's head (fonts, colours light and dark, base styles)
// from @ludify/deck's src/shell.html, then src/form/form.html (the form's own styles) and the
// bundled src/form/form.ts. Writes src/form.gen.ts, which the Worker imports.
// Usage: node scripts/build-form.ts
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const here = (p: string) => fileURLToPath(new URL(p, import.meta.url));

const shell = await readFile(here('../../deck/src/shell.html'), 'utf8');
const cut = shell.indexOf('\n/* top bar');
if (cut < 0 || !shell.slice(0, cut).includes('<style>') || !shell.includes('<title>Brief</title>'))
  throw new Error("The deck's shell.html changed shape; update scripts/build-form.ts to match.");
const head = shell.slice(0, cut).replace('<title>Brief</title>', '<title>Ludify</title>');

const out = await build({ entryPoints: [here('../src/form/form.ts')], bundle: true, format: 'iife', write: false, minify: true, target: 'es2022', charset: 'utf8' });
const script = out.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');

const html = '<!doctype html>\n<html lang="en">\n' + head + '\n'
  + await readFile(here('../src/form/form.html'), 'utf8')
  + `<script>${script}</script>\n`;

await writeFile(here('../src/form.gen.ts'), `// Generated by scripts/build-form.ts; do not edit.\nexport const FORM_HTML = ${JSON.stringify(html)};\n`);
console.log(`src/form.gen.ts: form page ${html.length} bytes (script ${script.length})`);
